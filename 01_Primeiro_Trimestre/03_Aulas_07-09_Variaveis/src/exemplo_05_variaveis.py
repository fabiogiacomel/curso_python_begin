# Exemplo 05: Variáveis
# Variáveis são nomes para valores

# Criando variáveis (atribuição)
nome_do_curso = "Python 1"
ano_letivo = 2026

# Usando as variáveis
print("Bem-vindo ao curso:")
print(nome_do_curso)
print("Ano:")
print(ano_letivo)

# Mudando o valor da variável
ano_letivo = 2027
print("Ano atualizado:")
print(ano_letivo)
