# Exemplo 14: Condicional Simples (if)

print("--- INÍCIO ---")
pontos = 1000

# Teste com valores diferentes aqui
pontos = 500

if pontos >= 1000:
    print("PARABÉNS!")
    print("Você ganhou um bônus!")
    print("Nova fase liberada.")

print("--- FIM ---")
# Note que o "FIM" aparece sempre,
# mas o "PARABÉNS" só aparece se tiver 1000 pontos ou mais.
