# Exemplo 01: While Simples

print("--- Contando de 1 a 10 ---")

numero = 1

while numero <= 10:
    print(f"Contagem: {numero}")
    numero = numero + 1 # Aumenta 1. Se tirar essa linha, trava tudo!

print("--- Decolagem! ---")
# Contagem regressiva
foguete = 10

while foguete >= 0:
    print(foguete)
    foguete = foguete - 1 # Diminui 1

print("FOGO!")
